import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const playbackUrl = 'data:text/javascript;base64,' + Buffer.from(fs.readFileSync('src/utils/playback.js', 'utf8')).toString('base64');
const moviesUrl = 'data:text/javascript;base64,' + Buffer.from(fs.readFileSync('src/utils/movies.js', 'utf8')).toString('base64');
const src = fs.readFileSync('src/services/playlist.js', 'utf8').replace("'../utils/playback'", JSON.stringify(playbackUrl)).replace("'../utils/movies'", JSON.stringify(moviesUrl));
const { parseM3U, validUrl } = await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'));
const list = parseM3U('#EXTM3U\n#EXTINF:-1 group-title="Sports",News\nhttps://example.com/live.m3u8\n#EXTINF:-1 group-title="Movies",Film\nfilm.mp4\n#EXTINF:-1 group-title="Series",Episode\nepisode.mkv', 'https://example.com/list.m3u');
assert.equal(list.length, 3);
assert.deepEqual(list.map(x => x.category), ['live', 'vod', 'series']);
assert.equal(list[1].url, 'https://example.com/film.mp4');
assert.throws(() => validUrl('file:///secret'));
assert.throws(() => parseM3U('<html/>', 'https://example.com'));
const pathList = parseM3U('#EXTM3U\n#EXTINF:-1 group-title="English",Drama\nhttps://example.com/movie/user/pass/1.ts\n#EXTINF:-1 group-title="English",Show\nhttps://example.com/series/user/pass/2.m3u8\n#EXTINF:-1 group-title="Sports",Channel\nhttps://example.com/live/user/pass/3.ts\n#EXTINF:-1 group-title="News",News\nhttps://example.com/channel?redirect=/movie/test.mp4', 'https://example.com/get.php');
assert.deepEqual(pathList.map(item => item.category), ['vod', 'series', 'live', 'live']);
assert.equal(pathList[0].url, 'https://example.com/movie/user/pass/1.ts');
console.log('M3U provider paths correctly classify movies, series and live without changing playback URLs.');
console.log('Playlist parser checks passed');
const { loadPlaylist, loadEpisodes, loadSeriesDetails } = await import('data:text/javascript;base64,' + Buffer.from(src).toString('base64'));
const originalFetch = globalThis.fetch;
globalThis.fetch = async uri => {
  const action = new URL(uri).searchParams.get('action');
  const body = !action ? { user_info: { auth: 1 } } : action.endsWith('_categories') ? [{ category_id: '1', category_name: 'Featured' }] : action === 'get_series_info' ? { episodes: { '1': [{ id: 21, title: 'Episode one', container_extension: 'mp4' }] } } : action === 'get_series' ? [{ series_id: 3, name: 'Series', category_id: '1', last_modified: '1793448000' }] : [{ stream_id: action === 'get_live_streams' ? 1 : 2, name: 'Stream', category_id: '1' }];
  return { ok: true, json: async () => body };
};
try {
  const config = { type: 'xtream', server: 'https://example.com', username: 'test user', password: 'p&ss' };
  const library = await loadPlaylist(config);
  assert.equal(library.length, 3);
  assert.equal(library[2].updatedAt, 1793448000000);
  assert.equal(Object.hasOwn(library[1], 'updatedAt'), false);
  assert.equal(Object.hasOwn(library[0], 'updatedAt'), false);
  assert.equal(library[2].metadata, undefined);
  const seriesSource = fs.readFileSync('src/utils/series.js', 'utf8').replace("'./movies'", JSON.stringify(moviesUrl));
  const { recentSeries } = await import('data:text/javascript;base64,' + Buffer.from(seriesSource).toString('base64'));
  const testNow = 1793448000000 + 86400000;
  assert.deepEqual(recentSeries(library, '', testNow).map(item => item.id), ['series:3']);
  const datedM3u = parseM3U('#EXTM3U\n#EXTINF:-1 group-title="Drama" last-modified="1793448000",Updated show\nhttps://example.com/series/u/p/1.ts', 'https://example.com/list');
  assert.equal(datedM3u[0].updatedAt, 1793448000000);
  assert.equal(recentSeries(datedM3u, '', testNow).length, 1);
  assert.equal(library.filter(item => item.category === 'vod').length, 1);
  assert.equal(library.filter(item => item.category === 'series').length, 1);
  assert.equal(library[0].group, 'Featured');
  assert.match(library[0].url, /test%20user\/p%26ss/);
  const episodes = await loadEpisodes(config, library[2]);
  assert.equal(episodes[0].name, 'Episode one');
  assert.match(episodes[0].url, /series\/test%20user\/p%26ss\/21.mp4$/);
  assert.equal(episodes[0].season, '1');
  assert.equal(episodes[0].seriesId, library[2].id);
  globalThis.fetch = async () => ({ ok: true, json: async () => ({ info: { plot: 'Series story', genre: 'Drama' }, episodes: { '2': [{ id: 22, episode_num: 2, info: { duration_secs: 1800 } }], '0': [{ id: 20 }], broken: null } }) });
  const details = await loadSeriesDetails(config, library[2]);
  assert.equal(details.metadata.summary, 'Series story');
  assert.equal(details.episodes.length, 2);
  assert.equal(details.episodes.find(item => item.season === '2').metadata.durationSeconds, 1800);
  const m3u = await loadSeriesDetails({ type: 'm3u' }, list[2]);
  assert.equal(m3u.episodes[0].url, list[2].url);
  assert.equal(m3u.episodes[0].season, 'unknown');
  globalThis.fetch = async uri => ({ ok: true, json: async () => new URL(uri).searchParams.get('action') ? [] : { user_info: { auth: 1 } } });
  await assert.rejects(() => loadPlaylist(config), /empty library/);
  console.log('Xtream seasons, metadata, episodes, empty-provider rejection and M3U fallback checks passed');
} finally { globalThis.fetch = originalFetch; }

