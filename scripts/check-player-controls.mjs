import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync('src/utils/playerControls.js', 'utf8');
const { formatPlaybackTime, clampPlaybackPosition, positionFromTouch } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.equal(formatPlaybackTime(0), '0:00');
assert.equal(formatPlaybackTime(75.9), '1:15');
assert.equal(formatPlaybackTime(3661), '1:01:01');
assert.equal(formatPlaybackTime(-5), '0:00');
assert.equal(formatPlaybackTime(NaN), '0:00');
assert.equal(positionFromTouch(50, 100, 7200), 3600);
assert.equal(positionFromTouch(-20, 100, 7200), 0);
assert.equal(positionFromTouch(120, 100, 7200), 7200);
assert.equal(positionFromTouch(20, 0, 7200), null);
assert.equal(positionFromTouch(20, 100, 0), null);
assert.equal(positionFromTouch(20, 100, Infinity), null);
assert.equal(positionFromTouch(NaN, 100, 7200), null);
assert.equal(clampPlaybackPosition(-10, 600), 0);
assert.equal(clampPlaybackPosition(700, 600), 600);
assert.equal(clampPlaybackPosition(20, NaN), null);
console.log('Timeline clock formatting, touch seeking, duration validation and seek bounds passed.');
