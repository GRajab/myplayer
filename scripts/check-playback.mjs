import fs from 'node:fs';
import assert from 'node:assert/strict';
const url = source => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
const playbackUrl = url(fs.readFileSync('src/utils/playback.js', 'utf8'));
const { parsePlaybackUrl, playbackSource, alternateLiveUrl, playbackFailure } = await import(playbackUrl);
const moviesUrl = url(fs.readFileSync('src/utils/movies.js', 'utf8'));
const { parseM3U } = await import(url(fs.readFileSync('src/services/playlist.js', 'utf8').replace("'../utils/playback'", JSON.stringify(playbackUrl)).replace("'../utils/movies'", JSON.stringify(moviesUrl))));
const parsed = parsePlaybackUrl('channel.m3u8?token=a%2Bb|User-Agent=My%20TV&Referer=https%3A%2F%2Fexample.com%2F&Origin=https%3A%2F%2Fexample.com', 'https://example.com/list.m3u');
assert.equal(parsed.url, 'https://example.com/channel.m3u8?token=a%2Bb');
assert.equal(parsed.headers['User-Agent'], 'My TV');
assert.equal(parsed.headers.Referer, 'https://example.com/');
assert.equal(playbackSource({ url: parsed.url, headers: parsed.headers }).contentType, 'hls');
assert.equal(playbackSource({ url: 'https://example.com/video.ts' }).contentType, 'auto');
assert.equal(playbackSource({ url: 'https://example.com/video.mpd?token=x' }).contentType, 'dash');
assert.throws(() => playbackSource({ url: 'file:///secret' }));
assert.deepEqual(parsePlaybackUrl('https://example.com/stream|User-Agent=a%0D%0Ab').headers, {});
const playlist = '#EXTM3U\n#EXTINF:-1 group-title="News",News\n#EXTVLCOPT:http-user-agent=Provider Player\n#EXTVLCOPT:http-referrer=https://example.com/\nhttps://example.com/live.m3u8|Origin=https%3A%2F%2Fexample.com\n#EXTINF:-1,Next\nhttps://example.com/next.m3u8';
const channels = parseM3U(playlist, 'https://example.com/list.m3u');
assert.equal(channels[0].headers['User-Agent'], 'Provider Player');
assert.equal(channels[0].headers.Referer, 'https://example.com/');
assert.equal(channels[0].headers.Origin, 'https://example.com');
assert.deepEqual(channels[1].headers, {});
const stream = { category: 'live', url: 'https://example.com/live/user/pass/42.m3u8?token=abc' };
assert.equal(alternateLiveUrl(stream, { type: 'xtream' }), 'https://example.com/live/user/pass/42.ts?token=abc');
assert.equal(alternateLiveUrl(stream, { type: 'm3u' }), null);
assert.equal(alternateLiveUrl({ ...stream, category: 'vod' }, { type: 'xtream' }), null);
assert.equal(alternateLiveUrl({ ...stream, url: 'https://example.com/other.m3u8' }, { type: 'xtream' }), null);
assert.match(playbackFailure({ message: 'Source error Response code: 403 https://example.com/user/SECRET' }), /403/);
assert.doesNotMatch(playbackFailure({ message: 'Unknown error https://example.com/user/SECRET' }), /SECRET|https/);
assert.match(playbackFailure({ message: 'CLEARTEXT communication not permitted' }), /HTTP playback blocked/);
assert.match(playbackFailure({ message: 'SocketTimeoutException' }), /timed out/);
assert.match(playbackFailure({ message: 'Decoder failed ERROR_CODE_DECODING_FAILED' }), /decode/);
console.log('Playback headers, M3U directives, format detection, safe alternate streams and credential-safe diagnostics passed.');
